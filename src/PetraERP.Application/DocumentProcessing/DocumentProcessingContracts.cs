using PetraERP.Application.Common;
using PetraERP.Application.Purchases;
using PetraERP.Application.Sales;
using PetraERP.Application.Treasury;

namespace PetraERP.Application.DocumentProcessing;

public enum DocumentProcessingOutcome
{
    SavedDraft = 0,
    ApprovalPermissionMissing = 1,
    Approved = 2,
    PostingPermissionMissing = 3,
    Posted = 4,
    PostingFailed = 5,
    AlreadyPosted = 6,
    /// <summary>The draft was saved, but the approve phase failed; DocumentId/Version identify the saved draft.</summary>
    ApprovalFailed = 7
}

/// <summary>What the initiating user may do under the effective server-side grants. Never inferred from the client.</summary>
public sealed record DocumentProcessingPermissions(bool CanApprove, bool CanPost)
{
    public static DocumentProcessingPermissions None { get; } = new(false, false);
}

/// <summary>The key that makes an uncertain posting safe to retry. Never regenerated by the server.</summary>
public sealed record DocumentPostingIntent(string IdempotencyKey, string? ManualNumber = null, string? Notes = null)
{
    public bool ConfirmCreditWarning { get; init; }
    public bool OverrideCreditPolicy { get; init; }
    public string? CreditOverrideReason { get; init; }

    /// <summary>Required only when the company policy allows a negative stock issue and the line exceeds availability.</summary>
    public string? NegativeStockReason { get; init; }
}

public sealed record DocumentProcessingResult(
    string DocumentType,
    Guid DocumentId,
    string? DocumentNumber,
    string Status,
    DocumentProcessingOutcome Outcome,
    bool ApprovalApplied,
    bool PostingApplied,
    Guid? JournalEntryId,
    string EffectivePostingMode,
    string Version)
{
    public string? Message { get; init; }
    public string? FailureCode { get; init; }
}

/// <summary>Document-type capability. A capability that is false is refused, never silently treated as supported.</summary>
public sealed record DocumentCapability(
    string DocumentType,
    bool SupportsDraft,
    bool SupportsApproval,
    bool SupportsPosting,
    bool SupportsAutomaticFinalization,
    bool RequiresSpecialConfirmation,
    string Note);

public static class DocumentCapabilityCatalog
{
    public static IReadOnlyList<DocumentCapability> All { get; } =
    [
        new("SalesInvoice", true, true, true, true, false, "Save → Approve → Post reuses the sales posting engine and its idempotency key."),
        new("PurchaseInvoice", true, true, true, true, false, "Save → Approve → Post reuses the purchase posting engine and its idempotency key."),
        new("CashReceiptVoucher", true, false, true, true, false, "Draft → Posted through save-and-process under ApproveAndPost with the post grant; ApproveOnly keeps the draft (vouchers have no approval step)."),
        new("CashPaymentVoucher", true, false, true, true, false, "Draft → Posted through save-and-process under ApproveAndPost with the post grant; ApproveOnly keeps the draft (vouchers have no approval step)."),
        new("JournalEntry", true, true, true, false, false, "Journals keep Draft → Validated → Approved → Posted; automatic finalization is not wired yet."),
        new("InventoryDocument", true, false, true, false, true, "Inventory states vary by document type; automatic finalization is not wired."),
        new("OpeningBalance", true, true, true, false, true, "Opening balances keep their dedicated approval workflow."),
        new("Reversal", false, true, true, false, true, "Reversals and corrections are never auto-posted.")
    ];

    public static DocumentCapability Get(string documentType)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(documentType);
        return All.FirstOrDefault(c => string.Equals(c.DocumentType, documentType, StringComparison.Ordinal))
            ?? throw new BusinessRuleException("document.unsupported_type", $"Document type '{documentType}' has no posting capability declaration.");
    }
}

/// <summary>
/// Orchestrates save, authorization-checked approval and posting through the existing document services.
/// It is not a second posting engine: every financial effect still comes from the document-specific service.
/// </summary>
public interface IDocumentSaveAndProcessService
{
    Task<DocumentProcessingResult> CreateSalesInvoiceAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, CreateSalesInvoiceCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);

    Task<DocumentProcessingResult> UpdateSalesInvoiceAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, Guid invoiceId, UpdateSalesInvoiceCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);

    Task<DocumentProcessingResult> CreatePurchaseInvoiceAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, SavePurchaseInvoiceCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);

    Task<DocumentProcessingResult> UpdatePurchaseInvoiceAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, Guid invoiceId, SavePurchaseInvoiceCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);

    /// <summary>Treasury vouchers: Draft → Posted (vouchers have no approval step). ApproveOnly keeps the draft.</summary>
    Task<DocumentProcessingResult> CreateVoucherAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, SaveVoucherCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);

    Task<DocumentProcessingResult> UpdateVoucherAsync(Guid companyId, Guid branchId, Guid userId,
        DocumentProcessingPermissions permissions, Guid voucherId, SaveVoucherCommand command, bool saveAsDraft,
        DocumentPostingIntent? posting, CancellationToken cancellationToken = default);
}
