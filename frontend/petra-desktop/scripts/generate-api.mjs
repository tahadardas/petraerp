// Generates the typed API schema from the committed OpenAPI contract (the same document the C# client is generated from).
// `npm run api:generate` writes src/services/api/schema.d.ts; `npm run api:check` fails when the committed file has drifted.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const contract = path.resolve(here, "../../../src/PetraERP.ApiClient/openapi/petraerp-v1.json");
const output = path.resolve(here, "../src/services/api/schema.d.ts");
const check = process.argv.includes("--check");

const ast = await openapiTS(new URL(`file:///${contract.replace(/\\/g, "/")}`), { exportType: true });
const banner = "// <auto-generated> from src/PetraERP.ApiClient/openapi/petraerp-v1.json by scripts/generate-api.mjs. Do not edit. </auto-generated>\n";
const text = (banner + astToString(ast)).replace(/\r\n/g, "\n");

if (check) {
  const current = existsSync(output) ? readFileSync(output, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("API schema drift: run `npm run api:generate` and commit the result.");
    process.exit(1);
  }
  console.log("PASS: the TypeScript API schema matches the OpenAPI contract.");
} else {
  writeFileSync(output, text, "utf8");
  console.log(`Wrote ${path.relative(process.cwd(), output)} (${text.length} bytes).`);
}
